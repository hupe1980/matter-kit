//! The IR, written out as Rust.
//!
//! One module per cluster, one per device type, and a `mod.rs` that names them. Everything is
//! `const`, macro-free and sorted: `const` so a device pays only for what it references,
//! macro-free so rustc scales linearly with 128 clusters rather than quadratically, and sorted
//! so `cargo xtask check` compares a byte at a time.

use std::fmt::Write as _;

use crate::ident;
use crate::model::{
    Attribute, Bitmap, Cluster, Command, Condition, Conform, DataModel, Enumeration, Event, Field,
    Structure, Verdict,
};
use crate::types::{Resolved, Types};

/// The banner every generated file carries.
fn header(version: &str, what: &str) -> String {
    format!(
        "// Generated by `cargo xtask` from the CSA data model {version}. Do not edit.\n\
         //\n\
         // {what}\n\
         //\n\
         // Regenerate with `cargo xtask clusters --dm <checkout>/data_model/{version}`; \
         `cargo xtask check`\n\
         // is the CI gate that keeps this file honest. The XML itself is not vendored here \
         — it\n\
         // carries the CSA's own copyright notice and is not redistributable.\n\n"
    )
}

/// Generates every file. The key is a filename relative to the output directory.
pub fn emit(model: &DataModel) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut cluster_modules: Vec<(String, &Cluster)> = Vec::new();
    let mut names: Vec<String> = model
        .clusters
        .iter()
        .map(|cluster| ident::snake(&cluster.name))
        .collect();
    ident::unique(&mut names);
    let module_of: std::collections::BTreeMap<u32, String> = model
        .clusters
        .iter()
        .map(|c| c.id)
        .zip(names.iter().cloned())
        .collect();
    let types = Types::index(model, &module_of);
    for (name, cluster) in names.iter().zip(&model.clusters) {
        files.push((
            format!("{name}.rs"),
            cluster_file(model, cluster, name, &types),
        ));
        cluster_modules.push((name.clone(), cluster));
    }

    let mut device_names: Vec<String> = model
        .device_types
        .iter()
        .map(|device| ident::snake(&device.name))
        .collect();
    ident::unique(&mut device_names);
    files.push((
        "device_types.rs".to_owned(),
        device_types_file(model, &device_names),
    ));

    files.push(("mod.rs".to_owned(), mod_file(model, &cluster_modules)));
    files.sort_by(|a, b| a.0.cmp(&b.0));
    files
}

// --- mod.rs -------------------------------------------------------------------------------

fn mod_file(model: &DataModel, modules: &[(String, &Cluster)]) -> String {
    let mut out = header(&model.version, "Every cluster the specification defines.");
    out.push_str(
        "//! The Matter cluster library, generated from the CSA data model.\n\
         //!\n\
         //! One module per cluster. Each holds the cluster's identifiers, its feature bits,\n\
         //! its enumerations and bitmaps as Rust types, and a [`Cluster`](crate::dm::spec::Cluster)\n\
         //! carrying every element the specification defines with its conformance, access and\n\
         //! qualities.\n\
         //!\n\
         //! These are the specification's tables, not a device's configuration. What a device\n\
         //! serves is a [`ClusterDescriptor`](crate::dm::ClusterDescriptor), and\n\
         //! [`Cluster::validate`](crate::dm::spec::Cluster::validate) is what checks one\n\
         //! against the other — the drift that certification finds, found at home instead.\n\n",
    );
    for (name, cluster) in modules {
        if cluster.is_base {
            let _ = writeln!(
                out,
                "/// {} — an abstract base: the types the clusters derived from it share,\n\
                 /// with no cluster id of its own.\npub mod {name};",
                ident::doc(&cluster.name),
            );
        } else {
            let _ = writeln!(
                out,
                "/// {} — cluster `{:#06X}`.\npub mod {name};",
                ident::doc(&cluster.name),
                cluster.id
            );
        }
    }
    out.push_str("\npub mod device_types;\n\n");

    out.push_str(
        "/// Every cluster in the library, sorted by id.\n\
         ///\n\
         /// **Referencing this links all of them.** Each table on its own is `const` data the\n\
         /// linker drops when nothing names it — one cluster costs about 8 KB of read-only\n\
         /// data, the whole library about 131 KB, measured on a release build. So a\n\
         /// controller or a conformance tool uses `ALL` and pays for it happily, and a device\n\
         /// names the handful of clusters it serves and pays for those.\n\
         ///\n\
         /// [`crate::clusters::validate_endpoint`] reaches `ALL` through [`find`], which is\n\
         /// why it belongs in a device's *tests* rather than its start-up path.\n",
    );
    let _ = writeln!(
        out,
        "pub const ALL: &[&crate::dm::spec::Cluster] = &[\n{}];\n",
        modules
            .iter()
            .filter(|(_, cluster)| !cluster.is_base)
            .map(|(name, _)| format!("    &{name}::CLUSTER,\n"))
            .collect::<String>()
    );

    out.push_str(
        "/// The specification's definition of a cluster, by id.\n\
         ///\n\
         /// Linear over 128 entries, which is nothing next to what a caller does with the\n\
         /// answer — and a sorted binary search would be one `unsafe`-free `expect` away from\n\
         /// a table that is sorted by construction anyway.\n\
         #[must_use]\n\
         pub fn find(id: crate::im::ClusterId) -> Option<&'static crate::dm::spec::Cluster> {\n\
         \x20   ALL.iter().copied().find(|cluster| cluster.id == id)\n\
         }\n",
    );
    out
}

// --- One cluster ----------------------------------------------------------------------------

fn cluster_file(model: &DataModel, cluster: &Cluster, module: &str, types: &Types) -> String {
    let mut out = header(
        &model.version,
        &format!(
            "{} — cluster {:#06X}.",
            ident::doc(&cluster.name),
            cluster.id
        ),
    );
    let _ = writeln!(
        out,
        "//! {} (cluster `{:#06X}`, revision {}).\n//!\n\
         //! {} identifiers, {} feature bits, and the specification's own conformance for\n\
         //! every element. `CLUSTER` is the whole table.\n",
        ident::doc(&cluster.name),
        cluster.id,
        cluster.revision,
        cluster.attributes.len() + cluster.commands.len() + cluster.events.len(),
        cluster.features.len(),
    );
    let _ = writeln!(out, "#![allow(unused_imports)]\n");
    out.push_str(
        "use crate::dm::conformance::{Clause, Condition, Conform, Conformance};\n\
         use crate::dm::meta::{EventPriority, Reporting};\n\
         use crate::dm::spec::{Attribute, Cluster, Command, Event, Feature};\n\
         use crate::dm::{Access, AccessQualities, AttributeQualities, Privilege};\n\
         use crate::error::Result;\n\
         use crate::im::{AttributeId, ClusterId, CommandId, EventId};\n\
         use crate::tlv::{\n\
         \x20   ContainerKind, Element, FromTlv, Nullable, Tag, TlvList, TlvReader, ToTlv, \
         TlvWriter, Value,\n\
         };\n\n",
    );
    let _ = writeln!(
        out,
        "/// The cluster id.\npub const ID: ClusterId = {:#06X};\n",
        cluster.id
    );
    let _ = writeln!(
        out,
        "/// The highest revision the specification's history defines — what `ClusterRevision`\n\
         /// must report (Core §7.13.1).\npub const REVISION: u16 = {};\n",
        cluster.revision
    );
    if !cluster.pics.is_empty() {
        let _ = writeln!(
            out,
            "/// The PICS code, which a certification declaration names the cluster by.\n\
             pub const PICS: &str = {:?};\n",
            cluster.pics
        );
    }

    emit_features(&mut out, cluster);
    emit_ids(&mut out, cluster);
    emit_enums(&mut out, cluster);
    emit_bitmaps(&mut out, cluster);
    emit_structs(&mut out, cluster, types);
    emit_payloads(&mut out, cluster, types);
    if cluster.is_base {
        // An abstract base defines types for the clusters derived from it and is not a
        // cluster anything serves, so it has no table and no entry in `ALL`.
        let _ = module;
        return out;
    }
    emit_tables(&mut out, cluster);
    let _ = writeln!(
        out,
        "/// The whole cluster, as the specification defines it.\n\
         pub const CLUSTER: Cluster = Cluster {{\n\
         \x20   id: ID,\n\
         \x20   name: {:?},\n\
         \x20   revision: REVISION,\n\
         \x20   pics: {:?},\n\
         \x20   derived_from: {},\n\
         \x20   features: FEATURES,\n\
         \x20   attributes: ATTRIBUTES,\n\
         \x20   commands: COMMANDS,\n\
         \x20   events: EVENTS,\n\
         }};",
        cluster.name,
        cluster.pics,
        match &cluster.base_cluster {
            Some(base) => format!("Some({base:?})"),
            None => "None".to_owned(),
        }
    );
    let _ = module;
    out
}

fn emit_features(out: &mut String, cluster: &Cluster) {
    if cluster.features.is_empty() {
        out.push_str(
            "/// This cluster defines no features, so its `FeatureMap` is always zero.\n\
             pub const FEATURES: &[Feature] = &[];\n\n",
        );
        return;
    }
    out.push_str(
        "/// The `FeatureMap` bits (Core §7.13.2).\n\
         ///\n\
         /// A feature has conformance of its own: a device may not claim one the\n\
         /// specification forbids it alongside another.\n\
         pub mod feature {\n",
    );
    let mut names: Vec<String> = cluster
        .features
        .iter()
        .map(|f| ident::screaming(&f.name))
        .collect();
    ident::unique(&mut names);
    for (name, feature) in names.iter().zip(&cluster.features) {
        let summary = if feature.summary.is_empty() {
            format!(
                "`{}`, the cluster's feature bit {}.",
                feature.name, feature.bit
            )
        } else {
            ident::doc(&feature.summary)
        };
        let _ = writeln!(
            out,
            "    /// {summary}\n    ///\n    /// Code `{}`, bit {}.\n    pub const {name}: u32 = 1 << {};",
            feature.code, feature.bit, feature.bit
        );
    }
    out.push_str("}\n\n");

    out.push_str(
        "/// Every feature bit, with its conformance.\npub const FEATURES: &[Feature] = &[\n",
    );
    for feature in &cluster.features {
        let _ = writeln!(
            out,
            "    Feature {{ bit: {}, code: {:?}, name: {:?}, conform: {} }},",
            feature.bit,
            feature.code,
            feature.name,
            conform_expr(cluster, &feature.conform)
        );
    }
    out.push_str("];\n\n");
}

fn emit_ids(out: &mut String, cluster: &Cluster) {
    emit_id_module(
        out,
        "attribute",
        "AttributeId",
        "The attribute ids.",
        cluster
            .attributes
            .iter()
            .map(|a| (a.name.as_str(), a.id, a.summary.as_str())),
    );
    emit_id_module(
        out,
        "command",
        "CommandId",
        "The command ids.",
        cluster
            .commands
            .iter()
            .map(|c| (c.name.as_str(), c.id, c.summary.as_str())),
    );
    emit_id_module(
        out,
        "event",
        "EventId",
        "The event ids.",
        cluster
            .events
            .iter()
            .map(|e| (e.name.as_str(), e.id, e.summary.as_str())),
    );
}

fn emit_id_module<'a>(
    out: &mut String,
    module: &str,
    kind: &str,
    doc: &str,
    entries: impl Iterator<Item = (&'a str, u32, &'a str)>,
) {
    let entries: Vec<_> = entries.collect();
    if entries.is_empty() {
        return;
    }
    let _ = writeln!(out, "/// {doc}\npub mod {module} {{");
    let _ = writeln!(out, "    use crate::im::{kind};\n");
    let mut names: Vec<String> = entries
        .iter()
        .map(|(name, _, _)| ident::screaming(name))
        .collect();
    ident::unique(&mut names);
    for (name, (spec_name, id, summary)) in names.iter().zip(&entries) {
        let width = if *id > 0xFF { 6 } else { 4 };
        // Always a doc line. A generated constant with none is a docs.rs page of bare names,
        // and the specification's own name is the thing a reader is looking for anyway.
        let summary = if summary.is_empty() {
            format!("`{spec_name}`.")
        } else {
            format!("`{spec_name}` — {}", ident::doc(summary))
        };
        let _ = writeln!(out, "    /// {summary}");
        let _ = writeln!(out, "    pub const {name}: {kind} = {id:#0width$X};");
    }
    out.push_str("}\n\n");
}

fn repr_for(max: u64) -> &'static str {
    if max <= u64::from(u8::MAX) {
        "u8"
    } else if max <= u64::from(u16::MAX) {
        "u16"
    } else if max <= u64::from(u32::MAX) {
        "u32"
    } else {
        "u64"
    }
}

fn emit_enums(out: &mut String, cluster: &Cluster) {
    for enumeration in &cluster.enums {
        emit_enum(out, enumeration);
    }
}

fn emit_enum(out: &mut String, enumeration: &Enumeration) {
    let name = ident::pascal(&enumeration.name);
    let max = enumeration.items.iter().map(|i| i.value).max().unwrap_or(0);
    let repr = repr_for(max);
    let mut variants: Vec<String> = enumeration
        .items
        .iter()
        .map(|item| ident::pascal(&item.name))
        .collect();
    ident::unique(&mut variants);

    let _ = writeln!(
        out,
        "/// `{}`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         #[repr({repr})]\n\
         pub enum {name} {{",
        enumeration.name
    );
    for (variant, item) in variants.iter().zip(&enumeration.items) {
        let summary = if item.summary.is_empty() {
            format!("`{}`.", item.name)
        } else {
            ident::doc(&item.summary)
        };
        let _ = writeln!(out, "    /// {summary}");
        let _ = writeln!(out, "    {variant} = {},", item.value);
    }
    out.push_str("}\n\n");

    // The wire form is an integer, and a value the enumeration does not define is not a
    // decoding error to swallow — §7.19.2's rule is that a reserved value is answered
    // `CONSTRAINT_ERROR`, which is the caller's decision to make from a `None`.
    let _ = writeln!(
        out,
        "impl {name} {{\n\
         \x20   /// Reads a wire value, or `None` for one this revision does not define.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn from_value(value: {repr}) -> Option<Self> {{\n\
         \x20       match value {{"
    );
    for (variant, item) in variants.iter().zip(&enumeration.items) {
        let _ = writeln!(out, "            {} => Some(Self::{variant}),", item.value);
    }
    let _ = writeln!(
        out,
        "            _ => None,\n\
         \x20       }}\n\
         \x20   }}\n\n\
         \x20   /// Its wire value.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn value(self) -> {repr} {{\n\
         \x20       self as {repr}\n\
         \x20   }}\n\
         }}\n"
    );
    // §7.19.2: "a reserved value SHALL be answered CONSTRAINT_ERROR". Decoding one as a
    // variant this revision happens to define would make the device's behaviour depend on
    // what a *future* revision assigns.
    let _ = writeln!(
        out,
        "impl ToTlv for {name} {{\n\
         \x20   fn to_tlv(&self, w: &mut TlvWriter<'_>, tag: Tag) -> Result<()> {{\n\
         \x20       self.value().to_tlv(w, tag)\n\
         \x20   }}\n\
         }}\n\n\
         impl<'a> FromTlv<'a> for {name} {{\n\
         \x20   fn from_tlv(reader: &mut TlvReader<'a>, element: &Element<'a>) -> Result<Self> {{\n\
         \x20       let value = <{repr} as FromTlv<'a>>::from_tlv(reader, element)?;\n\
         \x20       Self::from_value(value)\n\
         \x20           .ok_or(crate::Error::new(crate::ErrorCode::TlvOutOfRange))\n\
         \x20   }}\n\
         }}\n"
    );
}

fn emit_bitmaps(out: &mut String, cluster: &Cluster) {
    for bitmap in &cluster.bitmaps {
        emit_bitmap(out, bitmap);
    }
}

fn emit_bitmap(out: &mut String, bitmap: &Bitmap) {
    let name = ident::pascal(&bitmap.name);
    let max = bitmap
        .fields
        .iter()
        .map(|f| u64::from(f.bit))
        .max()
        .unwrap_or(0);
    let repr = if max < 8 {
        "u8"
    } else if max < 16 {
        "u16"
    } else if max < 32 {
        "u32"
    } else {
        "u64"
    };
    let mut names: Vec<String> = bitmap
        .fields
        .iter()
        .map(|field| ident::screaming(&field.name))
        .collect();
    ident::unique(&mut names);

    let _ = writeln!(
        out,
        "bitflags::bitflags! {{\n\
         \x20   /// `{}`.\n\
         \x20   #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n\
         \x20   pub struct {name}: {repr} {{",
        bitmap.name
    );
    for (constant, field) in names.iter().zip(&bitmap.fields) {
        let summary = if field.summary.is_empty() {
            format!("`{}`, bit {}.", field.name, field.bit)
        } else {
            ident::doc(&field.summary)
        };
        let _ = writeln!(out, "        /// {summary}");
        let _ = writeln!(out, "        const {constant} = 1 << {};", field.bit);
    }
    out.push_str("    }\n}\n\n");

    // A bit this revision does not define is refused rather than truncated away: §7.19.2's
    // reserved bits "SHALL be set to 0", and quietly clearing one would accept a command a
    // future revision gave a meaning to.
    let _ = writeln!(
        out,
        "impl ToTlv for {name} {{\n\
         \x20   fn to_tlv(&self, w: &mut TlvWriter<'_>, tag: Tag) -> Result<()> {{\n\
         \x20       self.bits().to_tlv(w, tag)\n\
         \x20   }}\n\
         }}\n\n\
         impl<'a> FromTlv<'a> for {name} {{\n\
         \x20   fn from_tlv(reader: &mut TlvReader<'a>, element: &Element<'a>) -> Result<Self> {{\n\
         \x20       let bits = <{repr} as FromTlv<'a>>::from_tlv(reader, element)?;\n\
         \x20       Self::from_bits(bits).ok_or(crate::Error::new(crate::ErrorCode::TlvOutOfRange))\n\
         \x20   }}\n\
         }}\n"
    );
}

// --- The element tables ---------------------------------------------------------------------

fn emit_tables(out: &mut String, cluster: &Cluster) {
    out.push_str("/// Every attribute the specification defines, with its conformance.\npub const ATTRIBUTES: &[Attribute] = &[\n");
    for attribute in &cluster.attributes {
        let _ = writeln!(
            out,
            "    Attribute {{ id: {:#06X}, name: {:?}, kind: {:?}, access: {}, qualities: {}, reporting: {}, conform: {} }},",
            attribute.id,
            attribute.name,
            type_name(attribute),
            access_expr(attribute),
            qualities_expr(attribute),
            reporting_expr(attribute),
            conform_expr(cluster, &attribute.conform)
        );
    }
    out.push_str("];\n\n");

    out.push_str("/// Every command, with its conformance.\npub const COMMANDS: &[Command] = &[\n");
    for command in &cluster.commands {
        // The XML says `commandToServer` or `responseFromServer`; a response belongs in the
        // *generated* list, and accepting one would advertise that a client may invoke this
        // server's own reply.
        let to_server = command.direction != "responseFromServer";
        let response = response_id(cluster, command);
        let _ = writeln!(
            out,
            "    Command {{ id: {:#04X}, name: {:?}, to_server: {to_server}, response: {response}, access: {}, conform: {} }},",
            command.id,
            command.name,
            command_access_expr(command),
            conform_expr(cluster, &command.conform)
        );
    }
    out.push_str("];\n\n");

    out.push_str("/// Every event, with its conformance.\npub const EVENTS: &[Event] = &[\n");
    for event in &cluster.events {
        let priority = match event.priority.as_str() {
            "debug" => "EventPriority::Debug",
            "critical" => "EventPriority::Critical",
            _ => "EventPriority::Info",
        };
        let _ = writeln!(
            out,
            "    Event {{ id: {:#04X}, name: {:?}, priority: {priority}, access: {}, conform: {} }},",
            event.id,
            event.name,
            event_access_expr(event),
            conform_expr(cluster, &event.conform)
        );
    }
    out.push_str("];\n\n");
}

/// The specification's type name for an attribute, list entries included.
fn type_name(attribute: &Attribute) -> String {
    match (&attribute.kind, &attribute.entry) {
        (kind, Some(entry)) if kind == "list" => format!("list[{entry}]"),
        (kind, _) => kind.clone(),
    }
}

/// A response command's id, when the XML names one.
fn response_id(cluster: &Cluster, command: &Command) -> String {
    if command.response.is_empty() || command.response == "Y" || command.response == "N" {
        return "None".to_owned();
    }
    match cluster
        .commands
        .iter()
        .find(|other| other.name == command.response)
    {
        Some(other) => format!("Some({:#04X})", other.id),
        // A response defined in another cluster — the Mode Base derivations do this. The id
        // is not knowable from here, and inventing one would be worse than saying nothing.
        None => "None".to_owned(),
    }
}

fn privilege(name: Option<&String>, fallback: &str) -> String {
    let level = match name.map(String::as_str) {
        Some("view") => "View",
        Some("operate") => "Operate",
        Some("manage") => "Manage",
        Some("admin") => "Administer",
        _ => fallback,
    };
    format!("Privilege::{level}")
}

fn access_qualities(
    fabric_scoped: bool,
    fabric_sensitive: bool,
    timed: bool,
    large: bool,
) -> Option<String> {
    let mut parts = Vec::new();
    if fabric_scoped {
        parts.push("AccessQualities::FABRIC_SCOPED");
    }
    if fabric_sensitive {
        parts.push("AccessQualities::FABRIC_SENSITIVE");
    }
    if timed {
        parts.push("AccessQualities::TIMED");
    }
    if large {
        parts.push("AccessQualities::LARGE");
    }
    if parts.is_empty() {
        None
    } else {
        Some(parts.join(".union(") + &")".repeat(parts.len() - 1))
    }
}

fn access_expr(attribute: &Attribute) -> String {
    let access = &attribute.access;
    let read = privilege(access.read_privilege.as_ref(), "View");
    // Every attribute in the 1.6 library is readable, and §7.6's default when the XML says
    // nothing is `R V`. An unreadable-but-writable one would still be expressible, and this
    // is what would notice it rather than quietly granting a read.
    debug_assert!(access.read || !access.write, "a write-only attribute");
    let base = if access.write {
        format!(
            "Access::read_write_with({read}, {})",
            privilege(access.write_privilege.as_ref(), "Operate")
        )
    } else {
        format!("Access::read_only({read})")
    };
    // An attribute's `L` is not an access constraint: §14.4.5.2 has a large attribute *shrink*
    // on a datagram transport rather than be refused, so gating the read would be wrong.
    match access_qualities(
        access.fabric_scoped,
        access.fabric_sensitive,
        access.timed,
        false,
    ) {
        Some(qualities) => format!("{base}.with_qualities({qualities})"),
        None => base,
    }
}

fn command_access_expr(command: &Command) -> String {
    let base = format!(
        "Access::invoke({})",
        privilege(command.access.invoke_privilege.as_ref(), "Operate")
    );
    match access_qualities(
        command.access.fabric_scoped,
        command.access.fabric_sensitive,
        command.access.timed,
        command.access.large,
    ) {
        Some(qualities) => format!("{base}.with_qualities({qualities})"),
        None => base,
    }
}

fn event_access_expr(event: &Event) -> String {
    let base = format!(
        "Access::read_only({})",
        privilege(event.access.read_privilege.as_ref(), "View")
    );
    match access_qualities(
        event.access.fabric_scoped,
        event.access.fabric_sensitive,
        false,
        false,
    ) {
        Some(qualities) => format!("{base}.with_qualities({qualities})"),
        None => base,
    }
}

fn qualities_expr(attribute: &Attribute) -> String {
    let quality = &attribute.quality;
    let mut parts = Vec::new();
    if quality.nullable {
        parts.push("AttributeQualities::NULLABLE");
    }
    if quality.persistence.as_deref() == Some("nonVolatile") {
        parts.push("AttributeQualities::NON_VOLATILE");
    }
    if quality.persistence.as_deref() == Some("fixed") {
        parts.push("AttributeQualities::FIXED");
    }
    if quality.atomic {
        parts.push("AttributeQualities::ATOMIC");
    }
    if quality.large {
        parts.push("AttributeQualities::LARGE");
    }
    if quality.scene {
        parts.push("AttributeQualities::SCENE");
    }
    if parts.is_empty() {
        "AttributeQualities::empty()".to_owned()
    } else {
        parts.join(".union(") + &")".repeat(parts.len() - 1)
    }
}

fn reporting_expr(attribute: &Attribute) -> String {
    if attribute.quality.changes_omitted {
        "Reporting::ChangesOmitted".to_owned()
    } else if attribute.quality.quieter {
        "Reporting::Quieter".to_owned()
    } else {
        "Reporting::OnChange".to_owned()
    }
}

// --- Conformance ------------------------------------------------------------------------------

fn conform_expr(cluster: &Cluster, conform: &Conform) -> String {
    if conform.clauses.len() == 1 {
        let clause = &conform.clauses[0];
        if clause.when == Condition::Always {
            return match clause.verdict {
                Verdict::Mandatory => "Conform::MANDATORY".to_owned(),
                Verdict::Optional => "Conform::OPTIONAL".to_owned(),
                Verdict::Disallowed => "Conform::DISALLOWED".to_owned(),
                Verdict::Described => "Conform::DESCRIBED".to_owned(),
                other => format!(
                    "Conform {{ clauses: &[Clause::always({})] }}",
                    verdict_expr(other)
                ),
            };
        }
    }
    let clauses = conform
        .clauses
        .iter()
        .map(|clause| {
            format!(
                "Clause {{ verdict: {}, when: {} }}",
                verdict_expr(clause.verdict),
                condition_expr(cluster, &clause.when)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("Conform {{ clauses: &[{clauses}] }}")
}

fn verdict_expr(verdict: Verdict) -> &'static str {
    match verdict {
        Verdict::Mandatory => "Conformance::Mandatory",
        Verdict::Optional => "Conformance::Optional",
        Verdict::Provisional => "Conformance::Provisional",
        Verdict::Deprecated => "Conformance::Deprecated",
        Verdict::Disallowed => "Conformance::Disallowed",
        Verdict::Described => "Conformance::Described",
    }
}

fn condition_expr(cluster: &Cluster, condition: &Condition) -> String {
    match condition {
        Condition::Always => "Condition::Always".to_owned(),
        Condition::Feature(code) => match cluster
            .features
            .iter()
            .find(|f| f.code == *code || f.name == *code)
        {
            Some(feature) => format!("Condition::Feature({})", feature.bit),
            // A feature this cluster does not define — a derived cluster naming its base's, or
            // a scraper slip. Recorded by name so the validator reports it as prose rather
            // than resolving it to a bit that means something else.
            None => format!("Condition::Named({code:?})"),
        },
        Condition::Attribute(name) => match cluster.attributes.iter().find(|a| a.name == *name) {
            Some(attribute) => format!("Condition::Attribute({:#06X})", attribute.id),
            None => format!("Condition::Named({name:?})"),
        },
        Condition::Command(name) => match cluster.commands.iter().find(|c| c.name == *name) {
            Some(command) => format!("Condition::Command({:#04X})", command.id),
            None => format!("Condition::Named({name:?})"),
        },
        Condition::Event(name) => match cluster.events.iter().find(|e| e.name == *name) {
            Some(event) => format!("Condition::Event({:#04X})", event.id),
            None => format!("Condition::Named({name:?})"),
        },
        Condition::Cluster(name) => format!("Condition::Named({name:?})"),
        // A sibling field. The runtime's `Supports` answers about a *cluster's* elements and
        // has no view inside one structure, so this is recorded by name and evaluates to
        // `Described` — the specification's own words decide, which for "unicast or groupcast,
        // never both" is what a reader needs anyway.
        Condition::Field(name) => format!("Condition::Named({:?})", format!("field:{name}")),
        Condition::Named(name) => format!("Condition::Named({name:?})"),
        Condition::Not(inner) => format!("Condition::Not(&{})", condition_expr(cluster, inner)),
        Condition::All(terms) => format!("Condition::All(&[{}])", term_list(cluster, terms)),
        Condition::Any(terms) => format!("Condition::Any(&[{}])", term_list(cluster, terms)),
        Condition::ExactlyOne(terms) => {
            format!("Condition::ExactlyOne(&[{}])", term_list(cluster, terms))
        }
        // Unreachable: a clause holding one became `Described` in the parser.
        Condition::Comparison => "Condition::Named(\"comparison\")".to_owned(),
    }
}

fn term_list(cluster: &Cluster, terms: &[Condition]) -> String {
    terms
        .iter()
        .map(|term| condition_expr(cluster, term))
        .collect::<Vec<_>>()
        .join(", ")
}

