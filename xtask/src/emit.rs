fn device_types_file(model: &DataModel, names: &[String]) -> String {
    let mut out = header(
        &model.version,
        "Every device type the Device Library defines.",
    );
    out.push_str(
        "//! The Matter device types (Device Library), generated from the CSA data model.\n\
         //!\n\
         //! A device type says which clusters an endpoint must and may serve, and sometimes\n\
         //! narrows a cluster further — On/Off Light requires On/Off *with* its Lighting\n\
         //! feature. `Descriptor`'s `DeviceTypeList` is what advertises one; this is what\n\
         //! says whether the endpoint behind it is furnished correctly.\n\n\
         #![allow(unused_imports)]\n\n\
         use crate::dm::conformance::{Clause, Condition, Conform, Conformance};\n\
         use crate::dm::device::{DeviceType, RequiredCluster};\n\
         use crate::im::ClusterId;\n\n",
    );

    let mut all = String::new();
    for (name, device) in names.iter().zip(&model.device_types) {
        let constant = ident::screaming(&device.name);
        let _ = writeln!(
            out,
            "/// {} — device type `{:#06X}`, revision {}.\n\
             pub const {constant}: DeviceType = DeviceType {{\n\
             \x20   id: {:#06X},\n\
             \x20   name: {:?},\n\
             \x20   revision: {},\n\
             \x20   class: {:?},\n\
             \x20   scope: {:?},\n\
             \x20   clusters: &[",
            ident::doc(&device.name),
            device.id,
            device.revision,
            device.id,
            device.name,
            device.revision,
            device.class,
            device.scope
        );
        for cluster in &device.clusters {
            let _ = writeln!(
                out,
                "        RequiredCluster {{ id: {:#06X}, name: {:?}, server: {}, conform: {}, features: {}, attributes: {}, commands: {}, events: {} }},",
                cluster.id,
                cluster.name,
                cluster.side != "client",
                device_conform_expr(&cluster.conform),
                requirement_list(&cluster.features),
                requirement_list(&cluster.attributes),
                requirement_list(&cluster.commands),
                requirement_list(&cluster.events),
            );
        }
        out.push_str("    ],\n};\n\n");
        let _ = writeln!(all, "    &{constant},");
        let _ = name;
    }

    let _ = writeln!(
        out,
        "/// Every device type, sorted by id.\n\
         pub const ALL: &[&DeviceType] = &[\n{all}];\n"
    );
    out.push_str(
        "/// The device type with this id, if the library defines one.\n\
         #[must_use]\n\
         pub fn find(id: u32) -> Option<&'static DeviceType> {\n\
         \x20   ALL.iter().copied().find(|device| device.id == id)\n\
         }\n",
    );
    out
}

/// A device type's conformance never refers to features by code, so there is no cluster to
/// resolve against.
fn device_conform_expr(conform: &Conform) -> String {
    let empty = Cluster {
        id: 0,
        name: String::new(),
        revision: 0,
        pics: String::new(),
        base_cluster: None,
        is_base: true,
        features: Vec::new(),
        enums: Vec::new(),
        bitmaps: Vec::new(),
        structs: Vec::new(),
        typedefs: Vec::new(),
        attributes: Vec::new(),
        commands: Vec::new(),
        events: Vec::new(),
    };
    conform_expr(&empty, conform)
}

/// A device type's extra requirements on one cluster, as `(name, conformance)` pairs.
fn requirement_list(items: &[(String, Conform)]) -> String {
    if items.is_empty() {
        return "&[]".to_owned();
    }
    let entries = items
        .iter()
        .map(|(name, conform)| format!("({name:?}, {})", device_conform_expr(conform)))
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{entries}]")
}

// --- Structures and command payloads ------------------------------------------------------

/// One field, resolved and named.
struct Member {
    /// The Rust field name.
    name: String,
    /// The specification's name, for the doc line.
    spec_name: String,
    /// Its context tag.
    tag: u8,
    /// The Rust type, already wrapped in `Option`/`Nullable` as its qualities require.
    rust: String,
    /// Whether the field may be absent.
    optional: bool,
    /// Whether it borrows.
    borrows: bool,
    /// The resolved base, for the decode arm.
    resolved: Resolved,
    nullable: bool,
}

/// Resolves a field list, or `None` if any field's type could not be mapped.
///
/// All or nothing on purpose. A structure with one field quietly missing is worse than no
/// structure at all: it decodes, it round-trips, and it silently drops whatever the field
/// carried — and the caller has no way to find out.
fn members(fields: &[Field], cluster: &Cluster, types: &Types) -> Option<Vec<Member>> {
    let mut names: Vec<String> = fields.iter().map(|f| ident::snake(&f.name)).collect();
    ident::unique(&mut names);
    let mut out = Vec::new();
    for (name, field) in names.into_iter().zip(fields) {
        let resolved = types.resolve(&field.kind, field.entry.as_deref(), cluster);
        if !resolved.is_known() {
            return None;
        }
        // §7.3's `O` on a field means it may be absent; §7.12's `X` means it may be null.
        // Both at once is three states, and `Option<Nullable<T>>` keeps all three.
        let optional =
            !field.conform.clauses.iter().any(|clause| {
                clause.verdict == Verdict::Mandatory && clause.when == Condition::Always
            });
        let mut rust = resolved.rust();
        if field.nullable {
            rust = format!("Nullable<{rust}>");
        }
        if optional {
            rust = format!("Option<{rust}>");
        }
        out.push(Member {
            name,
            spec_name: field.name.clone(),
            tag: field.id,
            rust,
            optional,
            borrows: resolved.borrows(),
            resolved,
            nullable: field.nullable,
        });
    }
    Some(out)
}

/// Writes a `struct` with its `ToTlv` and `FromTlv`.
fn emit_struct(out: &mut String, name: &str, doc: &str, members: &[Member], borrows: bool) {
    let lifetime = if borrows { "<'a>" } else { "" };
    let _ = writeln!(out, "/// {doc}");
    let _ = writeln!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq)]\npub struct {name}{lifetime} {{"
    );
    for member in members {
        let _ = writeln!(
            out,
            "    /// `{}`, field {}.\n    pub {}: {},",
            member.spec_name, member.tag, member.name, member.rust
        );
    }
    if members.is_empty() {
        // A command with no fields still needs a type, so that `invoke` has something to
        // decode into and the generated code has one shape rather than two.
        let _ = writeln!(
            out,
            "    /// This structure has no fields.\n    pub _empty: (),"
        );
    }
    out.push_str("}\n\n");

    // --- ToTlv ---
    let _ = writeln!(
        out,
        "impl{lifetime} ToTlv for {name}{lifetime} {{\n\
         \x20   fn to_tlv(&self, w: &mut TlvWriter<'_>, tag: Tag) -> Result<()> {{\n\
         \x20       w.start_structure(tag)?;"
    );
    for member in members {
        if member.optional {
            let _ = writeln!(
                out,
                "        if let Some(value) = &self.{} {{\n\
                 \x20           value.to_tlv(w, Tag::Context({}))?;\n\
                 \x20       }}",
                member.name, member.tag
            );
        } else {
            let _ = writeln!(
                out,
                "        self.{}.to_tlv(w, Tag::Context({}))?;",
                member.name, member.tag
            );
        }
    }
    out.push_str("        w.end_container()\n    }\n}\n\n");

    // --- FromTlv ---
    let read_lifetime = if borrows { "'a" } else { "'_" };
    let _ = writeln!(
        out,
        "impl<'a> FromTlv<'a> for {name}{lifetime} {{\n\
         \x20   fn from_tlv(reader: &mut TlvReader<'a>, element: &Element<'a>) -> Result<Self> {{\n\
         \x20       if element.value.container() != Some(ContainerKind::Structure) {{\n\
         \x20           return Err(crate::Error::new(crate::ErrorCode::TlvWrongType));\n\
         \x20       }}"
    );
    let _ = read_lifetime;
    for member in members {
        let _ = writeln!(out, "        let mut {} = None;", member.name);
    }
    out.push_str(
        "        loop {\n\
         \x20           let Some(field) = reader.next_element()? else {\n\
         \x20               return Err(crate::Error::new(crate::ErrorCode::TlvTruncated));\n\
         \x20           };\n\
         \x20           if field.value == Value::EndOfContainer {\n\
         \x20               break;\n\
         \x20           }\n\
         \x20           match field.tag.context() {\n",
    );
    for member in members {
        let ty = if member.nullable {
            format!("Nullable<{}>", member.resolved.rust())
        } else {
            member.resolved.rust()
        };
        let _ = writeln!(
            out,
            "                Some({}) => {} = Some(<{ty}>::from_tlv(reader, &field)?),",
            member.tag, member.name
        );
    }
    out.push_str(
        "                // A field this revision does not define. §7.19.2: a receiver\n\
         \x20               // ignores what it does not know rather than refusing the whole\n\
         \x20               // structure, which is what lets a newer peer talk to an older one.\n\
         \x20               _ => reader.skip_value(&field)?,\n\
         \x20           }\n\
         \x20       }\n",
    );
    out.push_str("        Ok(Self {\n");
    for member in members {
        if member.optional {
            let _ = writeln!(out, "            {},", member.name);
        } else {
            let _ = writeln!(
                out,
                "            {}: {}.ok_or(crate::Error::new(crate::ErrorCode::TlvNotFound))?,",
                member.name, member.name
            );
        }
    }
    if members.is_empty() {
        out.push_str("            _empty: (),\n");
    }
    out.push_str("        })\n    }\n}\n\n");
}

fn emit_structs(out: &mut String, cluster: &Cluster, types: &Types) {
    for structure in &cluster.structs {
        emit_one_struct(out, structure, cluster, types);
    }
}

fn emit_one_struct(out: &mut String, structure: &Structure, cluster: &Cluster, types: &Types) {
    let Some(mut members) = members(&structure.fields, cluster, types) else {
        let _ = writeln!(
            out,
            "// `{}` is not generated: one of its fields has a type with no Rust mapping.\n",
            structure.name
        );
        return;
    };
    if structure.fabric_scoped {
        // §7.19.1.9's global field. The XML never lists it — every fabric-scoped structure has
        // it, so saying so would be noise — and a generated type without it produces entries
        // that belong to no fabric, which is the whole basis of §6.6's isolation.
        members.push(Member {
            name: "fabric_index".to_owned(),
            spec_name: "FabricIndex".to_owned(),
            tag: 254,
            rust: "crate::msg::FabricIndex".to_owned(),
            optional: false,
            borrows: false,
            resolved: Resolved::Scalar("crate::msg::FabricIndex".to_owned()),
            nullable: false,
        });
    }
    let name = ident::pascal(&structure.name);
    let borrows = types.struct_borrows(cluster, &structure.name);
    let doc = if structure.fabric_scoped {
        format!(
            "`{}`, fabric-scoped — §7.19.1.9's `FabricIndex` is field 254.",
            structure.name
        )
    } else {
        format!("`{}`.", structure.name)
    };
    emit_struct(out, &name, &doc, &members, borrows);
}

/// Writes a payload type for every command that takes fields.
fn emit_payloads(out: &mut String, cluster: &Cluster, types: &Types) {
    let mut names: Vec<String> = cluster
        .commands
        .iter()
        .map(|command| format!("{}Fields", ident::pascal(&command.name)))
        .collect();
    ident::unique(&mut names);
    for (name, command) in names.iter().zip(&cluster.commands) {
        if command.fields.is_empty() {
            continue;
        }
        let Some(members) = members(&command.fields, cluster, types) else {
            let _ = writeln!(
                out,
                "// `{}`'s fields are not generated: one has a type with no Rust mapping.\n",
                command.name
            );
            continue;
        };
        let borrows = members.iter().any(|m| m.borrows);
        let doc = format!(
            "The fields of `{}` (command `{:#04X}`).",
            command.name, command.id
        );
        emit_struct(out, name, &doc, &members, borrows);
    }
}
