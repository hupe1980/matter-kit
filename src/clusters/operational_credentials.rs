/// The Operational Credentials cluster.
///
/// Holds nothing itself: the fabric table, the key store and the fail-safe are all node state
/// this cluster manipulates on the wire's behalf. That is what makes it shareable with CASE
/// (which needs the same fabric table) and with General Commissioning (which arms the same
/// fail-safe).
pub struct OperationalCredentials<'a, C: Config, K: KeyStore, R: Rng, const N: usize> {
    /// The fabric table — the `Fabrics`, `NOCs` and `TrustedRootCertificates` attributes.
    pub fabrics: &'a RefCell<FabricTable<C, N>>,
    /// Key custody. `CSRRequest` generates into it and `RemoveFabric` destroys from it.
    pub keys: &'a RefCell<K>,
    /// The node's one source of entropy, for `CSRRequest`'s key generation.
    ///
    /// A trait rather than raw bytes, because this is driven by the interaction model rather
    /// than called directly — and it is still a *parameter*, so a test installs a
    /// deterministic generator and gets a reproducible key.
    pub rng: &'a RefCell<R>,
    /// The fail-safe every credential-changing command runs inside (§11.10.7.2).
    pub fail_safe: &'a RefCell<crate::commissioning::failsafe::FailSafe>,
    /// This product's attestation material.
    pub attestation: DeviceAttestation<'a>,
    /// The root certificate installed by `AddTrustedRootCertificate` in the current fail-safe
    /// period, awaiting the `AddNOC` that will adopt it.
    pending_root: RefCell<Option<heapless::Vec<u8, OPERATIONAL_CERT_MAX>>>,
    /// The key pair generated by `CSRRequest` in this session, awaiting a NOC command.
    pending_csr: Cell<Option<PendingCsr>>,
    /// What the last credential-changing command left for the device.
    change: Cell<Option<FabricChange>>,
}

impl<'a, C: Config, K: KeyStore, R: Rng, const N: usize> OperationalCredentials<'a, C, K, R, N> {
    /// The cluster over a device's fabric table, key store and fail-safe.
    #[must_use]
    pub fn new(
        fabrics: &'a RefCell<FabricTable<C, N>>,
        keys: &'a RefCell<K>,
        rng: &'a RefCell<R>,
        fail_safe: &'a RefCell<crate::commissioning::failsafe::FailSafe>,
        attestation: DeviceAttestation<'a>,
    ) -> Self {
        Self {
            fabrics,
            keys,
            rng,
            fail_safe,
            attestation,
            pending_root: RefCell::new(None),
            pending_csr: Cell::new(None),
            change: Cell::new(None),
        }
    }

    /// Takes the work the last credential-changing command left behind.
    ///
    /// A device calls this after every invoke against this cluster. Forgetting to means a
    /// fabric is joined with no administrator able to reach it (§11.18.6.8 step 7), or a
    /// removed fabric's sessions stay open.
    #[must_use]
    pub fn take_change(&self) -> Option<FabricChange> {
        self.change.take()
    }

    /// Discards any fail-safe-scoped state, destroying the operational key a `CSRRequest`
    /// generated and nothing used.
    ///
    /// Call this when the fail-safe expires — it is §11.10.7.2.2 step 8, "the new operational
    /// key pair temporarily generated for the purposes of NOC addition or update … SHALL be
    /// removed as it is no longer needed" — and it is idempotent.
    pub fn discard_pending(&self) {
        *self.pending_root.borrow_mut() = None;
        if let Some(pending) = self.pending_csr.take() {
            let _ = self.keys.borrow_mut().remove(pending.key);
        }
    }

    /// Drops fail-safe-scoped state that belongs to a context which has since ended.
    ///
    /// The fail-safe's own [`Progress`](crate::commissioning::failsafe::Progress) is reset
    /// when a new context is armed, so a `csr_requested` that is no longer set means this
    /// cluster's pending key belongs to a period that is over. Checking it here is what keeps
    /// a stale key from being adopted by the *next* commissioner's `AddNOC`.
    fn reap(&self, now: crate::platform::Instant) {
        let progress = self
            .fail_safe
            .borrow()
            .armed(now)
            .map(|armed| armed.progress);
        let Some(progress) = progress else {
            self.discard_pending();
            return;
        };
        if !progress.csr_requested
            && let Some(pending) = self.pending_csr.take()
        {
            let _ = self.keys.borrow_mut().remove(pending.key);
        }
        if !progress.added_trusted_root {
            *self.pending_root.borrow_mut() = None;
        }
    }

    /// The fail-safe's progress, or `FAILSAFE_REQUIRED` when nothing is armed.
    ///
    /// Every credential-changing command starts here: §11.18.6.5, §11.18.6.8, §11.18.6.9 and
    /// §11.18.6.13 all say "If this command is received without an armed fail-safe context …
    /// then this command SHALL fail with a FAILSAFE_REQUIRED status code".
    fn require_fail_safe(
        &self,
        now: crate::platform::Instant,
    ) -> Result<crate::commissioning::failsafe::Progress, Status> {
        self.fail_safe
            .borrow()
            .armed(now)
            .map(|armed| armed.progress)
            .ok_or(Status::FailsafeRequired)
    }
}

