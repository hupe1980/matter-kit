/// `CertificateChainTypeEnum` (§11.18.4.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum CertificateChainType {
    /// `1` — "Request the DER-encoded DAC certificate".
    Dac = 1,
    /// `2` — "Request the DER-encoded PAI certificate".
    Pai = 2,
}

impl CertificateChainType {
    /// Decodes a wire value. §11.18.6.3: "If the CertificateType is not a valid value per
    /// CertificateChainTypeEnum then the command SHALL fail with a Status Code of
    /// INVALID_COMMAND" — note the *status*, not a response command, which is why this
    /// returns `None` rather than a third variant. Zero is not a value: the enumeration
    /// starts at one.
    #[must_use]
    pub const fn from_value(value: u8) -> Option<Self> {
        match value {
            1 => Some(Self::Dac),
            2 => Some(Self::Pai),
            _ => None,
        }
    }
}

/// `NodeOperationalCertStatusEnum` (§11.18.4.3).
///
/// Values 7 and 8 are absent from the specification's table, so they are absent here: a gap
/// in an enumeration is information, and filling it in would invent a status.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u8)]
#[non_exhaustive]
pub enum NocStatus {
    /// `0` — OK, no error.
    Ok = 0,
    /// `1` — "Public Key in the NOC does not match the public key in the NOCSR".
    InvalidPublicKey = 1,
    /// `2` — "The Node Operational ID in the NOC is not formatted correctly."
    InvalidNodeOpId = 2,
    /// `3` — "Any other validation error in NOC chain".
    InvalidNoc = 3,
    /// `4` — "No record of prior CSR for which this NOC could match".
    MissingCsr = 4,
    /// `5` — "NOCs table full, cannot add another one".
    TableFull = 5,
    /// `6` — "Invalid CaseAdminSubject field for an AddNOC command."
    InvalidAdminSubject = 6,
    /// `9` — "Trying to AddNOC instead of UpdateNOC against an existing Fabric."
    FabricConflict = 9,
    /// `10` — "Label already exists on another Fabric."
    LabelConflict = 10,
    /// `11` — "FabricIndex argument is invalid."
    InvalidFabricIndex = 11,
}

impl NocStatus {
    /// The value the enum encodes as.
    #[must_use]
    pub const fn value(self) -> u8 {
        self as u8
    }

    /// Whether this is [`NocStatus::Ok`].
    #[must_use]
    pub const fn is_ok(self) -> bool {
        matches!(self, Self::Ok)
    }
}

/// The device's attestation material — what §6.2's chain and §6.3's declaration are, for
/// this product.
///
/// Borrowed `&'static` in practice: the DAC and PAI are DER in flash, put there at
/// manufacture, and the Certification Declaration is the CMS blob the CSA signed.
#[derive(Debug, Clone, Copy)]
pub struct DeviceAttestation<'a> {
    /// The Device Attestation Certificate, DER-encoded (§6.2.2).
    pub dac: &'a [u8],
    /// The Product Attestation Intermediate, DER-encoded.
    pub pai: &'a [u8],
    /// The Certification Declaration — a CMS `SignedData`, DER-encoded (§6.3).
    pub certification_declaration: &'a [u8],
    /// A handle to the Device Attestation private key. Never the key.
    pub dac_key: KeyHandle,
    /// `firmware_information` (§6.3.2), if the product publishes one.
    pub firmware_information: Option<&'a [u8]>,
}

/// What an `AddNOC`, `UpdateNOC` or `RemoveFabric` left for the device to do.
///
/// Every variant is work outside a cluster's reach: the session table, the access-control
/// list, the DNS-SD advertisement. Reporting it keeps §11.18.6.8's eleven-step "Effect on
/// Receipt" checkable against the specification rather than scattered.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FabricChange {
    /// `AddNOC` succeeded (§11.18.6.8).
    Added {
        /// The index allocated for the new fabric.
        index: FabricIndex,
        /// Step 7: add an Access Control entry `{Privilege: Administer, AuthMode: CASE,
        /// Subjects: [this], Targets: []}` scoped to `index`.
        ///
        /// [`Acl::add_admin_for_fabric`](crate::acl::Acl::add_admin_for_fabric) builds exactly
        /// that entry — **do not skip it, and do not hand-build it**. §11.18.6.8: "Unless such
        /// an Access Control Entry is added atomically as described here, there would be no
        /// way for the caller on its given Fabric to eventually add another Access Control
        /// Entry for CASE authentication mode." The failure is silent and total: the fabric is
        /// joined, the node advertises itself, and the instant the PASE session closes nobody
        /// can administer it ever again.
        case_admin_subject: u64,
        /// Step 10a: whether the command arrived over PASE, in which case the session must be
        /// "augment … with the FabricIndex generated above, such that subsequent
        /// interactions have the proper accessing fabric".
        bind_pase_session: bool,
    },
    /// `UpdateNOC` succeeded (§11.18.6.9): re-advertise, and revoke everything tied to the
    /// previous operational identity — "except for the ongoing CASE session context, which
    /// SHALL temporarily remain valid until the NOCResponse has been successfully delivered".
    Updated {
        /// The fabric whose identity changed.
        index: FabricIndex,
    },
    /// `RemoveFabric` succeeded (§11.18.6.12).
    Removed {
        /// The fabric removed.
        index: FabricIndex,
        /// Whether it was the last one: "the device SHALL delete all Matter related data on
        /// the node which was created since it was commissioned" — a factory reset in all but
        /// name.
        was_last: bool,
        /// Whether it was the accessing fabric, in which case the session carrying this very
        /// response is among the things to be torn down.
        was_accessing: bool,
    },
}

/// A key pair generated by `CSRRequest` and not yet used by a NOC command (§11.18.6.5).
#[derive(Debug, Clone, Copy)]
struct PendingCsr {
    /// The session it was generated on. §11.18.6.7 scopes the record to a session, so one
    /// administrator's CSR cannot be consumed by another's `AddNOC`.
    session: Option<SessionId>,
    key: KeyHandle,
    public: PublicKey,
    /// `IsForUpdateNOC`: which of the two commands this key may be used by. Mixing them is
    /// `CONSTRAINT_ERROR` in both directions (§11.18.6.8, §11.18.6.9).
    for_update: bool,
}

