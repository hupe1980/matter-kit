//! Operational Credentials cluster `0x003E` (Core §11.18) — joining and leaving fabrics.
//!
//! > This cluster is used to add or remove Node Operational credentials on a Commissionee or
//! > already-configured Node, as well as manage the associated Fabrics.
//!
//! It is the cluster commissioning exists to reach. Everything before it — discovery, PASE,
//! the fail-safe, the regulatory configuration — is setup; this is where a device acquires an
//! identity it did not have.
//!
//! # The order is not a suggestion
//!
//! A commissioner must issue, inside one fail-safe period:
//!
//! 1. `AttestationRequest` — prove the device is a certified product (§6.2).
//! 2. `CertificateChainRequest` ×2 — fetch the DAC and PAI to check that proof against.
//! 3. `CSRRequest` — have the device generate an operational key it has never had before.
//! 4. `AddTrustedRootCertificate` — install the fabric's root.
//! 5. `AddNOC` — install the certificate the commissioner minted from the CSR.
//!
//! §11.18.6.8 makes each step's precondition explicit, and each one refuses rather than
//! improvises: no fail-safe is `FAILSAFE_REQUIRED`, a second `AddNOC` in one period is
//! `CONSTRAINT_ERROR`, a missing CSR is `MissingCsr`, a missing root is `InvalidNOC`. The
//! last is worth reading twice — "**AddNOC always requires that the client provides the root
//! of trust certificate within the same Fail-Safe context** as the rest of the new fabric's
//! operational credentials, **even if some other fabric already uses the exact same root**".
//! A device that reused an installed root would let an administrator graft a new fabric onto
//! a root it never presented.
//!
//! # Two secrets that never move
//!
//! The operational private key is generated by the device and leaves only as a public key in
//! a CSR; it lives in the [`KeyStore`](crate::crypto::KeyStore) as a handle. The `AttestationChallenge` is the
//! third key the session derived and "SHALL NOT be included in any of the payloads conveyed"
//! — it is what makes an `AttestationResponse` unreplayable, because a signature over it
//! proves the signer was on *this* session.
//!
//! # What this cluster does not own
//!
//! §11.18.6.8's effect on receipt reaches well past the fabric table: step 6 re-advertises
//! the node over DNS-SD, step 7 adds an Access Control entry for `CaseAdminSubject`, step 10
//! binds the accessing PASE session to the new fabric. None of those belong to a cluster, so
//! `AddNOC` reports a `FabricChange` and the device applies it — the same arrangement as
//! the fail-safe's [`Cleanup`](crate::commissioning::failsafe::Cleanup), and for the same
//! reason: the work is outside a cluster's reach, so the cluster reports it rather than
//! reaching for it.
//!
//! # Revision 2
//!
//! | Revision | Change |
//! |---|---|
//! | 1 | Initial revision |
//! | 2 | The Fabric Table Vendor ID Verification Procedure (§6.4.10) |

