/// The largest `NOCs` value a node with `fabrics` fabrics can produce, in octets.
///
/// A read builds one whole attribute value in a scratch buffer before the server decides
/// whether it fits a message or has to be split across several (§10.6.4.3.1) — so the scratch
/// is sized by the largest *value* a node can produce, which is not the largest *message* it
/// can send. Those are different numbers, and a value larger than a message is precisely the
/// case list chunking exists for.
///
/// This is the largest of them for most nodes: a non-fabric-filtered `NOCs` read carries every
/// fabric's NOC and ICAC, each capped at [`OPERATIONAL_CERT_MAX`] by §6.1.3, plus the
/// `NOCStruct` and array framing. Five fabrics is over four kilobytes — more than three times
/// a datagram — which a node that sized its scratch by "the biggest constant I had" discovers
/// as `ResourceExhausted` from its own cluster, with nothing on the wire to explain it.
#[must_use]
pub const fn max_nocs_len(fabrics: usize) -> usize {
    // Per entry: two certificates, their octet-string headers, the `FabricIndex` and the
    // structure's own control and end-of-container octets. Sixteen is generous for the
    // framing and keeps the arithmetic obvious.
    let per_fabric = OPERATIONAL_CERT_MAX.saturating_mul(2).saturating_add(16);
    // Plus the array's own control octet and end-of-container.
    per_fabric.saturating_mul(fabrics).saturating_add(8)
}

